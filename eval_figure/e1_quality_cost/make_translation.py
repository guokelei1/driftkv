"""SIMULATED DATA: add the per-release cache-translation baseline to frontier_data.json.

Cache translation applies the history-conditioned map of the motivation study
once per release and stores the translated K/V. It is swept over map width and
fitting budget. Values are invented layout previews derived from each panel's
own Reuse/Rebuild anchors; rerunning the script overwrites only this method.
"""
from pathlib import Path
import json

PATH = Path(__file__).with_name('frontier_data.json')
# Budget points (complete added FLOPs / Rebuild, %) and recovery (%) before the
# small per-configuration and per-release offsets below.
COST = [8.0, 14.0, 24.0, 38.0]
RECOVERY = [44.0, 56.0, 64.0, 68.0]
CONFIG_SHIFT = {('Yambda', 'Large'): 0.0, ('Yambda', 'Max'): -1.0,
                ('RecFlow', 'Large'): 1.0, ('RecFlow', 'Max'): -2.0}
RELEASE_SHIFT = {'V3': (-.35, -1.0), 'V4': (0.0, 1.0), 'V5': (.35, 0.0)}


def main():
    data = json.loads(PATH.read_text())
    assert data['meta']['synthetic'] is True
    for cfg in data['configurations']:
        shift = CONFIG_SHIFT[(cfg['dataset'], cfg['scale'])]
        for panel in cfg['release_panels']:
            dx, dy = RELEASE_SHIFT[panel['release']]
            low, high = panel['reuse_auc'], panel['rebuild_auc']
            panel['curves']['Cache translation'] = [
                [round(c + dx, 2),
                 round(low + (r + shift + dy) / 100 * (high - low), 5)]
                for c, r in zip(COST, RECOVERY)]
    data['meta']['cache_translation'] = (
        'Synthetic per-release history-conditioned K/V map, applied once per '
        'release and stored; generated by make_translation.py.')
    PATH.write_text(json.dumps(data, indent=2) + '\n')
    print(f'Updated {PATH}')


if __name__ == '__main__':
    main()
